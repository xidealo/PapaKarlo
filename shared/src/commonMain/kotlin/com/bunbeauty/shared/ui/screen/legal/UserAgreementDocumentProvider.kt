    Настоящий Сервис явно не использует cookies. Однако приложение может использовать сторонний код и библиотеки, которые используют cookies для сбора информации и улучшения своих сервисов. У вас есть возможность принять или отказаться от cookies, а также узнать, когда cookie отправляется на ваше устройство. Если вы откажетесь от cookies, некоторые части Сервиса могут быть недоступны.

